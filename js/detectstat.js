// detect.js と同じ判定(明るい・低彩度・十分明るい)
function isWhitePx(d, p) {
  const r = d[p], g = d[p + 1], b = d[p + 2];
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
  return mn > 140 && mx - mn < 60 && mx >= 150;
}

// テンプレ一致位置を左上から探す。probesで大半の候補を即座に棄却する
function findAnchor(img, tpl) {
  const { width: w, height: h, data: d } = img;
  if (w < tpl.w || h < tpl.h) return null;
  const mask = new Uint8Array(w * h);
  for (let i = 0, p = 0; i < w * h; i++, p += 4) mask[i] = isWhitePx(d, p) ? 1 : 0;
  const step = Math.max(1, (tpl.ink.length / 4) | 0);
  const probes = [tpl.ink[0], tpl.ink[step], tpl.ink[step * 2], tpl.ink[step * 3]];
  const at = (o, t) => mask[o + ((t / tpl.w) | 0) * w + (t % tpl.w)];
  for (let y = 0; y <= h - tpl.h; y++) {
    for (let x = 0; x <= w - tpl.w; x++) {
      const o = y * w + x;
      let quick = true;
      for (const t of probes) if (!at(o, t)) { quick = false; break; }
      if (!quick) continue;
      let ink = 0;
      for (const t of tpl.ink) if (at(o, t)) ink++;
      if (ink < tpl.ink.length * 0.94) continue;
      let holes = 0;
      for (const t of tpl.holes) if (!at(o, t)) holes++;
      if (holes >= tpl.holes.length * 0.8) return { x, y };
    }
  }
  return null;
}

function boxFrom(img, a, rect) {
  const bbox = { x: a.x + rect.dx, y: a.y + rect.dy, w: rect.w, h: rect.h };
  if (bbox.x < 0 || bbox.y < 0 || bbox.x + bbox.w > img.width || bbox.y + bbox.h > img.height) {
    return { error: 'clipped', bbox };
  }
  return bbox;
}

// 戻り値契約は findTooltip と同一: {x,y,w,h} または {error, bbox?}
// CaptureController.setDetector() にそのまま渡せる
export function findStatWindow(img) {
  const a = findAnchor(img, STAT_ANCHOR);
  return a ? boxFrom(img, a, STAT_ROWS) : { error: 'not_found' };
}

export function findStatPopup(img) {
  const a = findAnchor(img, POPUP_ANCHOR);
  return a ? boxFrom(img, a, POPUP_ROWS) : { error: 'not_found' };
}
